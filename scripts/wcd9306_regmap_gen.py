"""Generate mainline-style WCD9306 (Tapan) register tables from the vendor sources.

Usage: wcd9306_regmap_gen.py VENDOR_KERNEL_TREE OUTPUT_HEADER

Reads include/linux/mfd/wcd9xxx/wcd9306_registers.h (addresses and __POR
values) and sound/soc/codecs/wcd9306-tables.c (readable flags and reset
defaults), cross-checks them, and writes WCD9306_* register definitions, a
reg_default table and a readable bitmap. Exits non-zero on any inconsistency.
"""
import re
import sys
from pathlib import Path

NUM_REGS = 0x400


def parse_header(text):
    regs, por = {}, {}
    for name, val in re.findall(r'#define\s+TAPAN_A_(\w+?)\s+\((0x[0-9A-Fa-f]+)\)', text):
        if name.endswith('__POR'):
            por[name[:-5]] = int(val, 16)
        else:
            regs[name] = int(val, 16)
    return regs, por


def parse_table(text, table, por):
    body = re.search(r'const u8 %s\[TAPAN_CACHE_SIZE\] = \{(.*?)\n\};' % table, text, re.S)
    if not body:
        raise SystemExit('table %s not found' % table)
    out = {}
    for key, val in re.findall(r'\[TAPAN_A_(\w+)\]\s*=\s*([^,\n]+),', body.group(1)):
        val = val.strip()
        ref = re.fullmatch(r'TAPAN_A_(\w+)__POR', val)
        if ref:
            if ref.group(1) not in por:
                raise SystemExit('%s: unknown POR macro %s' % (table, val))
            out[key] = por[ref.group(1)]
        elif re.fullmatch(r'0x[0-9A-Fa-f]+|\d+', val):
            out[key] = int(val, 0)
        else:
            raise SystemExit('%s: cannot parse value %r for %s' % (table, val, key))
    return out


def main():
    tree, output = Path(sys.argv[1]), Path(sys.argv[2])
    regs, por = parse_header((tree / 'include/linux/mfd/wcd9xxx/wcd9306_registers.h').read_text())
    tables = (tree / 'sound/soc/codecs/wcd9306-tables.c').read_text()
    readable = parse_table(tables, 'tapan_reg_readable', por)
    defaults = parse_table(tables, 'tapan_reset_reg_defaults', por)
    if len(defaults) < sum(1 for v in readable.values() if v):
        raise SystemExit('reset-default table has %d entries for %d readable registers' % (len(defaults), sum(1 for v in readable.values() if v)))
    errors = []
    for name in list(readable) + list(defaults):
        if name not in regs:
            errors.append('unknown register %s' % name)
    for name, addr in regs.items():
        if addr >= NUM_REGS:
            errors.append('%s out of range 0x%x' % (name, addr))
    addr_names = {}
    for name, addr in regs.items():
        addr_names.setdefault(addr, []).append(name)
    for name, val in defaults.items():
        if name in por and por[name] != val:
            errors.append('%s: header POR 0x%02x, table default 0x%02x' % (name, por[name], val))
        if val and not readable.get(name):
            errors.append('%s: non-zero default on a register not marked readable' % name)
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        raise SystemExit(1)

    lines = ['/* SPDX-License-Identifier: GPL-2.0-only */',
             '/* Generated by scripts/wcd9306_regmap_gen.py from the LG Fx0 vendor kernel. */',
             '/* Copyright (c) 2012-2013, The Linux Foundation. All rights reserved. */',
             '#ifndef __WCD9306_REGS_H__', '#define __WCD9306_REGS_H__', '',
             '#define WCD9306_NUM_REGISTERS\t0x%x' % NUM_REGS,
             '#define WCD9306_MAX_REGISTER\t(WCD9306_NUM_REGISTERS - 1)', '']
    for name, addr in sorted(regs.items(), key=lambda kv: (kv[1], kv[0])):
        lines.append('#define WCD9306_%s\t0x%03x' % (name, addr))
    lines += ['', 'static const struct reg_default wcd9306_defaults[] = {']
    for name, addr in sorted(regs.items(), key=lambda kv: (kv[1], kv[0])):
        if readable.get(name) and addr_names[addr][0] == name:
            lines.append('\t{ WCD9306_%s, 0x%02x },' % (name, defaults.get(name, 0)))
    lines += ['};', '', 'static const u8 wcd9306_readable[WCD9306_NUM_REGISTERS] = {']
    for name, addr in sorted(regs.items(), key=lambda kv: (kv[1], kv[0])):
        if readable.get(name) and addr_names[addr][0] == name:
            lines.append('\t[WCD9306_%s] = 1,' % name)
    lines += ['};', '', '#endif /* __WCD9306_REGS_H__ */', '']
    output.write_text('\n'.join(lines))
    print('registers %d, readable %d, non-zero defaults %d, aliased addresses %d' % (
        len(regs), sum(1 for v in readable.values() if v),
        sum(1 for v in defaults.values() if v),
        sum(1 for v in addr_names.values() if len(v) > 1)))


if __name__ == '__main__':
    main()
