#!/usr/bin/env python3
"""Compile candidate Fx0 DTBs from pinned cached sources, without flashing."""

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]


def run(argv, cwd=None, stdout=None, stderr=None):
    return subprocess.run([str(x) for x in argv], cwd=cwd, stdout=stdout, stderr=stderr, check=True)


def verify_cache(cache):
    manifest = json.loads((ROOT / "manifests/source-files.json").read_text())
    for item in manifest["files"]:
        path = cache / item["source"] / item["path"]
        data = str(path.readlink()).encode() if path.is_symlink() else path.read_bytes()
        blob = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
        if blob != item["git_blob"]:
            raise RuntimeError(f"Pinned source mismatch: {item['source']}/{item['path']}")
    return manifest


def build_dtc(cache, output):
    source = cache / "linux/scripts/dtc"
    build = output / "dtc"
    build.mkdir(parents=True, exist_ok=True)
    run(["bison", "-d", "-o", build / "dtc-parser.tab.c", source / "dtc-parser.y"])
    run(["flex", "-o", build / "dtc-lexer.lex.c", source / "dtc-lexer.l"])
    files = ["dtc.c", "flattree.c", "fstree.c", "data.c", "livetree.c", "treesource.c", "srcpos.c", "checks.c", "util.c"]
    executable = build / "dtc"
    run(["gcc", "-O2", "-DNO_YAML", "-I" + str(source), "-I" + str(source / "libfdt"), "-I" + str(build), "-o", executable,
         *[source / name for name in files], build / "dtc-lexer.lex.c", build / "dtc-parser.tab.c"])
    return executable


def compile_dtb(cpp, dtc, source, includes, output, defines=()):
    preprocessed = output.with_suffix(".preprocessed.dts")
    warnings = output.with_suffix(".warnings.txt")
    with preprocessed.open("wb") as out:
        run([cpp, "-nostdinc", "-undef", "-D__DTS__", "-x", "assembler-with-cpp", *defines,
             *["-I" + str(path) for path in includes], source], stdout=out)
    with warnings.open("wb") as errors:
        run([dtc, "-I", "dts", "-O", "dtb", "-o", output, preprocessed], stderr=errors)
    decoded = output.with_suffix(".decoded.dts")
    with decoded.open("wb") as out:
        run([dtc, "-I", "dtb", "-O", "dts", output], stdout=out, stderr=subprocess.DEVNULL)
    return {
        "file": output.name,
        "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "bytes": output.stat().st_size,
        "warnings": warnings.read_text().count("Warning ("),
    }


def build(cache, output, cpp="cpp", linux_source="linux-stable"):
    manifest = verify_cache(cache)
    output.mkdir(parents=True, exist_ok=True)
    dtc = build_dtc(cache, output)
    trees = output / "trees"
    if trees.exists():
        marker = trees / ".fx0-generated"
        if not marker.is_file() or marker.read_text() != "Generated by build_device_trees.py\n":
            raise RuntimeError("Refusing to replace a source directory without the generated marker")
        shutil.rmtree(trees)
    trees.mkdir()
    (trees / ".fx0-generated").write_text("Generated by build_device_trees.py\n")
    for name in (linux_source, "lk2nd"):
        target = trees / name
        shutil.copytree(cache / name, target, symlinks=True)
        for patch in sorted((ROOT / "patches" / name).glob("*.patch")):
            run(["git", "apply", "--check", patch], cwd=target)
            run(["git", "apply", patch], cwd=target)
    linux = trees / linux_source
    lk2nd = trees / "lk2nd"
    qcom = linux / "arch/arm/boot/dts/qcom"
    results = []
    # Compile unchanged SoC/PMIC descriptions separately to distinguish inherited
    # dtc warnings from warnings introduced by the candidate board description.
    baseline = output / "msm8226-baseline.dts"
    baseline.write_text('/dts-v1/;\n#include "qcom-msm8226.dtsi"\n#include "pm8226.dtsi"\n')
    results.append(compile_dtb(cpp, dtc, baseline, [linux / "include", qcom], output / "msm8226-baseline.dtb"))
    results.append(compile_dtb(cpp, dtc, qcom / "qcom-msm8926-lg-madai.dts", [linux / "include", qcom], output / "qcom-msm8926-lg-madai.dtb"))
    results.append(compile_dtb(cpp, dtc, lk2nd / "lk2nd/device/dts/msm8226/msm8926-lg-madai.dts",
                               [lk2nd / "lk2nd/device/dts", lk2nd / "lk2nd/include"],
                               output / "lk2nd-msm8926-lg-madai.dtb", ['-D_DTB_NAME_="msm8926-lg-madai"']))
    def warnings(name):
        return Counter(line.split("Warning (", 1)[1] for line in (output / name).read_text().splitlines() if "Warning (" in line)
    new_warnings = list((warnings("qcom-msm8926-lg-madai.warnings.txt") - warnings("msm8226-baseline.warnings.txt")).elements())
    report = {
        "scope": "DTC compilation and patch application only; not schema, kernel, bootloader image, or physical-device qualification",
        "sources": manifest["sources"],
        "linux_source": linux_source,
        "results": results,
        "new_linux_warnings": new_warnings,
        "patches": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                    for name in (linux_source, "lk2nd") for p in sorted((ROOT / "patches" / name).glob("*.patch"))},
    }
    (output / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    if new_warnings:
        raise RuntimeError("Candidate DTS introduces compiler warnings; inspect report.json")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=ROOT / "local/source-cache")
    parser.add_argument("--output", type=Path, default=ROOT / "build/device-trees")
    parser.add_argument("--linux-source", choices=("linux", "linux-stable"), default="linux-stable")
    args = parser.parse_args()
    print(json.dumps(build(args.cache.resolve(), args.output.resolve(), linux_source=args.linux_source), indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"build-device-trees: {error}", file=sys.stderr)
        sys.exit(1)
